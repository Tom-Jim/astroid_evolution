//! Build-time shader pipeline.
//!
//! Every compute program is one WESL source under `src/**/shader/`. A file that
//! declares a `@compute` entry is a program; other files are libraries pulled in
//! with `// #include "path/from/src.wesl"`. A program that traces rays is built
//! twice through WESL conditional translation:
//!
//! * `rt_hw`  – hardware ray queries (`enable wgpu_ray_query;`), for the desktop;
//! * `!rt_hw` – the software BVH of `gpu/shader/rt.wesl`, for the browser and for a
//!   desktop GPU without ray tracing (or `AE_SOFT_RT=1`).
//!
//! The features `native_fp` and `fp_fma` select how the double-single library
//! forms its exact residuals (`gpu/shader/ds.wesl`): floating-point on the desktop
//! (fused `fma` on Metal, Dekker's product on Vulkan), integer arithmetic in the
//! browser.
//!
//! naga validates every variant (a shader error fails the build) and emits, per
//! entry point and for the target being compiled:
//!
//! * Linux/Windows: SPIR-V for Vulkan, loaded by wgpu as a passthrough module.
//! * macOS: Metal Shading Language (ray tracing through `intersection_query`),
//!   compiled by wgpu as a passthrough module, with safe floating-point math.
//! * wasm32: WGSL for WebGPU.
//!
//! Each module is compacted to what its entry point uses, and its bindings are
//! renumbered densely in binding order: wgpu's Vulkan and Metal backends number
//! descriptors and buffer slots of a bind group that way.
//!
//! The generated `kernels.rs` lists every entry point with its workgroup size and
//! its binding table, so the host binds arguments by position.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const MSL_VERSION: (u8, u8) = (3, 1);

#[derive(Clone, Copy, PartialEq, Eq)]
enum Target {
    Spirv,
    Msl,
    Wgsl,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Kind {
    Read,
    Write,
    Uniform,
    Accel,
    Bvh,
}

impl Kind {
    fn name(self) -> &'static str {
        match self {
            Kind::Read => "Read",
            Kind::Write => "Write",
            Kind::Uniform => "Uniform",
            Kind::Accel => "Accel",
            Kind::Bvh => "Bvh",
        }
    }
}

struct Entry {
    name: String,
    wg: [u32; 3],
    binds: Vec<(u32, Kind)>,
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("src");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let target = if arch == "wasm32" {
        Target::Wgsl
    } else if os == "macos" {
        Target::Msl
    } else {
        Target::Spirv
    };
    println!("cargo::rerun-if-changed=src/build.rs");
    println!("cargo::rerun-if-env-changed=AE_DS_EXACT");

    let mut programs = Vec::new();
    collect(&root, &mut programs);
    programs.sort();

    let mut rs = String::new();
    rs.push_str("// Generated by src/build.rs. Do not edit.\n\n");
    let mut seen_entries = BTreeSet::new();
    let mut order: Vec<String> = Vec::new();
    let mut units = Vec::new();
    for program in &programs {
        let mut files = BTreeSet::new();
        let source = expand(&root, program, &mut files);
        for f in &files {
            println!("cargo::rerun-if-changed={}", f.display());
        }
        units.extend(split_entries(&program_name(&root, program), &source));
    }
    for (stem, source) in &units {
        let stem = stem.clone();
        let source = source.clone();
        let traces = source.contains("@if(rt_hw)") || source.contains("@if(!rt_hw)");
        let native_fp = target != Target::Wgsl && std::env::var_os("AE_DS_EXACT").is_none();
        let fp = (native_fp, target == Target::Msl);
        let hw_src = translate(&source, true, traces, fp, &stem);
        let sw_src = if traces {
            translate(&source, false, traces, fp, &stem)
        } else {
            hw_src.clone()
        };
        std::fs::write(out.join(format!("{stem}.hw.wgsl")), &hw_src).unwrap();
        std::fs::write(out.join(format!("{stem}.sw.wgsl")), &sw_src).unwrap();
        let hw = parse(&hw_src, &stem, "rt_hw");
        let sw = if traces {
            parse(&sw_src, &stem, "sw")
        } else {
            parse(&hw_src, &stem, "rt_hw")
        };
        let hw_entries = entries(&hw.0, &hw.1);
        let sw_entries = entries(&sw.0, &sw.1);
        for (ei, e) in hw_entries.iter().enumerate() {
            assert!(
                seen_entries.insert(e.name.clone()),
                "entry point `{}` is defined by more than one program",
                e.name
            );
            let sw_e = &sw_entries[ei];
            assert_eq!(sw_e.name, e.name);
            let code = |module: &(naga::Module, naga::valid::ModuleInfo),
                        entry: &Entry,
                        tag: &str| {
                let name = &entry.name;
                match target {
                    Target::Spirv => {
                        eprintln!("SPIR-V {stem}.{name}.{tag}");
                        let path = out.join(format!("{stem}.{name}.{tag}.spv"));
                        std::fs::write(&path, write_spirv(&module.0, &module.1, entry)).unwrap();
                        format!(
                            "Code::Spirv(include_bytes!({:?}))",
                            path.display().to_string()
                        )
                    }
                    Target::Msl => {
                        let (m, i) = single_entry(&module.0, name, &stem);
                        let path = out.join(format!("{stem}.{name}.{tag}.metal"));
                        let (text, function) = write_msl(&m, &i, entry, &stem);
                        std::fs::write(&path, text).unwrap();
                        format!(
                            "Code::Msl(include_str!({:?}), {function:?})",
                            path.display().to_string()
                        )
                    }
                    Target::Wgsl => {
                        let (m, i) = single_entry(&module.0, name, &stem);
                        let path = out.join(format!("{stem}.{name}.{tag}.wgsl"));
                        let text = naga::back::wgsl::write_string(
                            &m,
                            &i,
                            naga::back::wgsl::WriterFlags::empty(),
                        )
                        .unwrap_or_else(|e| panic!("WGSL {stem}.{name}: {e}"));
                        // naga's namer appends `_` to an identifier that ends in a digit
                        // (`basis_vel_o4` -> `basis_vel_o4_`), but the host looks the entry
                        // point up by its source name.
                        let text = restore_entry_name(text, name);
                        std::fs::write(&path, text).unwrap();
                        format!("Code::Wgsl(include_str!({:?}))", path.display().to_string())
                    }
                }
            };
            // The browser has no hardware variant; every other target carries both.
            let sw_code = code(&sw, sw_e, "sw");
            let hw_code = if target == Target::Wgsl || !traces {
                sw_code.clone()
            } else {
                code(&hw, e, "hw")
            };
            let konst = e.name.to_uppercase();
            let id = order.len();
            order.push(konst.clone());
            let _ = writeln!(
                rs,
                "pub const {konst}: Kernel = Kernel {{ id: {id}, name: {:?}, wg: [{}, {}, {}], traces: {traces}, hw: Variant {{ binds: &[{}], code: {hw_code} }}, sw: Variant {{ binds: &[{}], code: {sw_code} }} }};",
                e.name,
                e.wg[0],
                e.wg[1],
                e.wg[2],
                binds_rs(&e.binds),
                binds_rs(&sw_e.binds),
            );
        }
    }
    let _ = writeln!(
        rs,
        "\n/// Every entry point, for lookup by name.\npub static ALL: &[&Kernel] = &[{}];",
        order
            .iter()
            .map(|n| format!("&{n}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    std::fs::write(out.join("kernels.rs"), rs).unwrap();
}

fn binds_rs(binds: &[(u32, Kind)]) -> String {
    binds
        .iter()
        .map(|(b, k)| format!("Bind {{ binding: {b}, kind: BindKind::{} }}", k.name()))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Gives the single `@compute` function of a generated WGSL module back its source name.
fn restore_entry_name(text: String, name: &str) -> String {
    let at = text
        .find("@compute")
        .expect("WGSL module without a compute entry");
    let fn_at = at + text[at..].find("fn ").expect("compute entry without `fn`") + 3;
    let end = fn_at
        + text[fn_at..]
            .find('(')
            .expect("compute entry without parameters");
    if &text[fn_at..end] == name {
        return text;
    }
    format!("{}{}{}", &text[..fn_at], name, &text[end..])
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            if path.ends_with("shader") {
                println!("cargo::rerun-if-changed={}", path.display());
            }
            collect(&path, out);
        } else if path.extension().is_some_and(|e| e == "wesl")
            && path.parent().is_some_and(|p| p.ends_with("shader"))
        {
            let text = std::fs::read_to_string(&path).unwrap();
            // Render shaders (Bevy materials) are compiled by Bevy itself.
            if text.contains("@compute") && !text.contains("#import bevy") {
                out.push(path);
            }
        }
    }
}

/// A program may hold several entry sections, `// ENTRY name` … `// END ENTRY name`,
/// whose globals would collide; each section is compiled with the rest of the file.
fn split_entries(stem: &str, source: &str) -> Vec<(String, String)> {
    if !source.contains("\n// ENTRY ") {
        return vec![(stem.to_string(), source.to_string())];
    }
    let mut shared = String::new();
    let mut sections: Vec<(String, String)> = Vec::new();
    let mut current: Option<(String, String)> = None;
    for line in source.lines() {
        if let Some(name) = line.strip_prefix("// ENTRY ") {
            assert!(current.is_none(), "{stem}: nested entry section {name}");
            current = Some((name.trim().to_string(), String::new()));
        } else if line.starts_with("// END ENTRY") {
            sections.push(
                current
                    .take()
                    .unwrap_or_else(|| panic!("{stem}: stray {line}")),
            );
        } else if let Some((_, text)) = current.as_mut() {
            text.push_str(line);
            text.push('\n');
        } else {
            shared.push_str(line);
            shared.push('\n');
        }
    }
    assert!(current.is_none(), "{stem}: unterminated entry section");
    sections
        .into_iter()
        .map(|(name, text)| (format!("{stem}_{name}"), format!("{shared}\n{text}")))
        .collect()
}

fn program_name(root: &Path, program: &Path) -> String {
    program
        .strip_prefix(root)
        .unwrap()
        .with_extension("")
        .to_string_lossy()
        .replace(['/', '\\'], "_")
        .replace("_shader_", "_")
}

/// Expand `// #include "path"` (relative to `src/`) once per file, depth first.
fn expand(root: &Path, file: &Path, seen: &mut BTreeSet<PathBuf>) -> String {
    if !seen.insert(file.to_path_buf()) {
        return String::new();
    }
    let text =
        std::fs::read_to_string(file).unwrap_or_else(|e| panic!("shader {}: {e}", file.display()));
    let mut out = String::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("// #include ") {
            let rel = rest.trim().trim_matches('"');
            out.push_str(&expand(root, &root.join(rel), seen));
            out.push('\n');
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// WESL conditional translation, then the ray-query directive for the hardware variant.
fn translate(
    source: &str,
    hw: bool,
    traces: bool,
    (native_fp, fp_fma): (bool, bool),
    stem: &str,
) -> String {
    use wesl::resolver::VirtualResolver;
    let mut resolver = VirtualResolver::new();
    let path: wesl::syntax::ModulePath = "package::main".parse().unwrap();
    resolver.add_module(path.clone(), std::borrow::Cow::Owned(source.to_string()));
    let mut options = wesl::CompileOptions::default();
    options.imports = false;
    options.validate = false;
    options.sourcemap = false;
    options.mangler = wesl::ManglerKind::None;
    options.strip = true;
    options.features.set("rt_hw", hw);
    options.features.set("native_fp", native_fp);
    options.features.set("fp_fma", fp_fma);
    options.features.set("metal", fp_fma);
    let compiled = wesl::compile(&path, &options, &resolver)
        .unwrap_or_else(|e| panic!("WESL {stem} (rt_hw={hw}): {e}"));
    let text = compiled.syntax.to_string();
    if hw && traces {
        format!("enable wgpu_ray_query;\n{text}")
    } else {
        text
    }
}

fn parse(src: &str, stem: &str, variant: &str) -> (naga::Module, naga::valid::ModuleInfo) {
    let mut module = naga::front::wgsl::parse_str(src).unwrap_or_else(|e| {
        let dump = std::env::temp_dir().join(format!("ae_shader_{stem}_{variant}.wgsl"));
        let _ = std::fs::write(&dump, src);
        panic!(
            "WGSL {stem} ({variant}), source in {}:\n{}",
            dump.display(),
            e.emit_to_string(src)
        )
    });
    let info = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::all(),
    )
    .validate(&module)
    .unwrap_or_else(|e| {
        let dump = std::env::temp_dir().join(format!("ae_shader_{stem}_{variant}.wgsl"));
        let _ = std::fs::write(&dump, src);
        panic!(
            "naga validation {stem} ({variant}), source in {}:\n{}",
            dump.display(),
            e.emit_to_string(src)
        )
    });
    if !copy_in_pointer_args(&mut module, &info) {
        return (module, info);
    }
    let info = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::all(),
    )
    .validate(&module)
    .unwrap_or_else(|e| panic!("{stem} ({variant}) after the pointer-argument rewrite: {e}"));
    (module, info)
}

/// naga 30's SPIR-V writer cannot pass a pointer into part of a variable
/// (`f(&v.field)`, `f(&a[i])`) to a function: such an argument is never emitted.
/// Rewrite each one as copy-in/copy-out through a fresh local variable, which is
/// the same thing for function-space memory nothing else aliases during the call.
fn copy_in_pointer_args(module: &mut naga::Module, info: &naga::valid::ModuleInfo) -> bool {
    use naga::{Expression, Statement};
    fn walk(
        block: naga::Block,
        f: &mut naga::Function,
        fi: &naga::valid::FunctionInfo,
        types: &naga::UniqueArena<naga::Type>,
        changed: &mut bool,
    ) -> naga::Block {
        let mut out = naga::Block::with_capacity(block.len());
        for (stmt, span) in block.span_into_iter() {
            let stmt = match stmt {
                Statement::Block(b) => Statement::Block(walk(b, f, fi, types, changed)),
                Statement::If {
                    condition,
                    accept,
                    reject,
                } => Statement::If {
                    condition,
                    accept: walk(accept, f, fi, types, changed),
                    reject: walk(reject, f, fi, types, changed),
                },
                Statement::Loop {
                    body,
                    continuing,
                    break_if,
                } => Statement::Loop {
                    body: walk(body, f, fi, types, changed),
                    continuing: walk(continuing, f, fi, types, changed),
                    break_if,
                },
                Statement::Switch { selector, cases } => Statement::Switch {
                    selector,
                    cases: cases
                        .into_iter()
                        .map(|mut c| {
                            c.body = walk(c.body, f, fi, types, changed);
                            c
                        })
                        .collect(),
                },
                Statement::Call {
                    function,
                    mut arguments,
                    result,
                } => {
                    let mut after = Vec::new();
                    for arg in arguments.iter_mut() {
                        let is_part = matches!(
                            f.expressions[*arg],
                            Expression::Access { .. } | Expression::AccessIndex { .. }
                        );
                        if !is_part {
                            continue;
                        }
                        let naga::TypeInner::Pointer {
                            base,
                            space: naga::AddressSpace::Function,
                        } = *fi[*arg].ty.inner_with(types)
                        else {
                            continue;
                        };
                        *changed = true;
                        let tmp = f.local_variables.append(
                            naga::LocalVariable {
                                name: None,
                                ty: base,
                                init: None,
                            },
                            span,
                        );
                        let lv = f.expressions.append(Expression::LocalVariable(tmp), span);
                        let load = f
                            .expressions
                            .append(Expression::Load { pointer: *arg }, span);
                        out.push(
                            Statement::Emit(naga::Range::new_from_bounds(load, load)),
                            span,
                        );
                        out.push(
                            Statement::Store {
                                pointer: lv,
                                value: load,
                            },
                            span,
                        );
                        let back = f.expressions.append(Expression::Load { pointer: lv }, span);
                        after.push((*arg, back));
                        *arg = lv;
                    }
                    out.push(
                        Statement::Call {
                            function,
                            arguments,
                            result,
                        },
                        span,
                    );
                    for (pointer, back) in after {
                        out.push(
                            Statement::Emit(naga::Range::new_from_bounds(back, back)),
                            span,
                        );
                        out.push(
                            Statement::Store {
                                pointer,
                                value: back,
                            },
                            span,
                        );
                    }
                    continue;
                }
                other => other,
            };
            out.push(stmt, span);
        }
        out
    }
    let mut changed = false;
    let handles: Vec<_> = module.functions.iter().map(|(h, _)| h).collect();
    for h in handles {
        let fi = &info[h];
        let f = &mut module.functions[h];
        let body = std::mem::take(&mut f.body);
        f.body = walk(body, f, fi, &module.types, &mut changed);
    }
    for i in 0..module.entry_points.len() {
        let fi = info.get_entry_point(i);
        let f = &mut module.entry_points[i].function;
        let body = std::mem::take(&mut f.body);
        f.body = walk(body, f, fi, &module.types, &mut changed);
    }
    changed
}

fn entries(module: &naga::Module, info: &naga::valid::ModuleInfo) -> Vec<Entry> {
    let mut out = Vec::new();
    for (i, ep) in module.entry_points.iter().enumerate() {
        if ep.stage != naga::ShaderStage::Compute {
            continue;
        }
        let fi = info.get_entry_point(i);
        let mut binds = BTreeMap::new();
        for (handle, var) in module.global_variables.iter() {
            // Every binding that survives WESL's dead-declaration strip, used by the
            // entry or not: callers bind by position over that interface.
            let Some(rb) = &var.binding else { continue };
            let _ = &fi[handle];
            assert_eq!(rb.group, 0, "all bindings live in group 0");
            let kind = match var.space {
                naga::AddressSpace::Uniform => Kind::Uniform,
                naga::AddressSpace::Storage { access } => {
                    if var.name.as_deref().is_some_and(|n| n.starts_with("rt_bvh")) {
                        Kind::Bvh
                    } else if access.contains(naga::StorageAccess::STORE) {
                        Kind::Write
                    } else {
                        Kind::Read
                    }
                }
                naga::AddressSpace::Handle => match module.types[var.ty].inner {
                    naga::TypeInner::AccelerationStructure { .. } => Kind::Accel,
                    ref other => panic!("unsupported handle binding {other:?}"),
                },
                other => panic!("unsupported binding space {other:?}"),
            };
            binds.insert(rb.binding, kind);
        }
        out.push(Entry {
            name: ep.name.clone(),
            wg: ep.workgroup_size,
            binds: binds.into_iter().collect(),
        });
    }
    out
}

fn write_spirv(module: &naga::Module, info: &naga::valid::ModuleInfo, entry: &Entry) -> Vec<u8> {
    let mut options = naga::back::spv::Options::default();
    options.lang_version = (1, 4);
    options.flags.remove(naga::back::spv::WriterFlags::DEBUG);
    options.force_loop_bounding = false;
    options.ray_query_initialization_tracking = false;
    options.bounds_check_policies = naga::proc::BoundsCheckPolicies {
        index: naga::proc::BoundsCheckPolicy::Unchecked,
        buffer: naga::proc::BoundsCheckPolicy::Unchecked,
        image_load: naga::proc::BoundsCheckPolicy::Unchecked,
        binding_array: naga::proc::BoundsCheckPolicy::Unchecked,
    };
    // wgpu's Vulkan backend numbers descriptors densely in binding order.
    for (dense, (binding, _)) in entry.binds.iter().enumerate() {
        options.binding_map.insert(
            naga::ResourceBinding {
                group: 0,
                binding: *binding,
            },
            naga::back::spv::BindingInfo {
                descriptor_set: 0,
                binding: dense as u32,
                binding_array_size: None,
            },
        );
    }
    let pipeline = naga::back::spv::PipelineOptions {
        shader_stage: naga::ShaderStage::Compute,
        entry_point: entry.name.clone(),
    };
    let words = naga::back::spv::write_vec(module, info, &options, Some(&pipeline))
        .unwrap_or_else(|e| panic!("SPIR-V {}: {e}", entry.name));
    no_contraction(&words)
        .iter()
        .flat_map(|w| w.to_le_bytes())
        .collect()
}

/// Decorate every floating-point arithmetic result `NoContraction`.
///
/// Without it a Vulkan compiler may fuse a multiply into an add and Mesa's NIR
/// may reassociate (`s - (s - a)` → `a`), which erases the error-free
/// transformations of the double-single library. The decoration makes each
/// operation exact as written; explicit `fma` calls are unaffected.
fn no_contraction(words: &[u32]) -> Vec<u32> {
    const OP_DECORATE: u32 = 71;
    const NO_CONTRACTION: u32 = 42;
    // OpFNegate, OpFAdd, OpFSub, OpFMul, OpFDiv, OpFRem, OpFMod,
    // OpVectorTimesScalar, OpMatrixTimesScalar, OpVectorTimesMatrix,
    // OpMatrixTimesVector, OpMatrixTimesMatrix, OpDot.
    const FLOAT_OPS: [u32; 13] = [
        127, 129, 131, 133, 136, 140, 141, 142, 143, 144, 145, 146, 148,
    ];
    let mut ids = Vec::new();
    let mut first_type = None;
    let mut at = 5;
    while at < words.len() {
        let count = (words[at] >> 16) as usize;
        let op = words[at] & 0xffff;
        if first_type.is_none() && (19..=39).contains(&op) {
            first_type = Some(at);
        }
        if FLOAT_OPS.contains(&op) {
            ids.push(words[at + 2]);
        }
        at += count.max(1);
    }
    let Some(insert) = first_type else {
        return words.to_vec();
    };
    let mut out = Vec::with_capacity(words.len() + 3 * ids.len());
    out.extend_from_slice(&words[..insert]);
    for id in ids {
        out.extend_from_slice(&[(3 << 16) | OP_DECORATE, id, NO_CONTRACTION]);
    }
    out.extend_from_slice(&words[insert..]);
    out
}

/// MSL of one entry point and the name naga gave its kernel function.
fn write_msl(
    module: &naga::Module,
    info: &naga::valid::ModuleInfo,
    e: &Entry,
    stem: &str,
) -> (String, String) {
    use naga::back::msl;
    let mut options = msl::Options::default();
    options.lang_version = MSL_VERSION;
    options.fake_missing_bindings = false;
    options.force_loop_bounding = false;
    options.ray_query_initialization_tracking = false;
    options.bounds_check_policies = naga::proc::BoundsCheckPolicies {
        index: naga::proc::BoundsCheckPolicy::Unchecked,
        buffer: naga::proc::BoundsCheckPolicy::Unchecked,
        image_load: naga::proc::BoundsCheckPolicy::Unchecked,
        binding_array: naga::proc::BoundsCheckPolicy::Unchecked,
    };
    // wgpu's Metal backend gives the buffers of a bind group consecutive slots in
    // binding order, the same dense numbering as on Vulkan.
    {
        let mut resources = msl::BindingMap::default();
        for (dense, (binding, kind)) in e.binds.iter().enumerate() {
            resources.insert(
                naga::ResourceBinding {
                    group: 0,
                    binding: *binding,
                },
                msl::BindTarget {
                    buffer: Some(dense as u8),
                    mutable: *kind == Kind::Write,
                    ..Default::default()
                },
            );
        }
        options.per_entry_point_map.insert(
            e.name.clone(),
            msl::EntryPointResources {
                resources,
                immediates_buffer: None,
                sizes_buffer: Some(e.binds.len() as u8),
            },
        );
    }
    let (text, translation) =
        msl::write_string(module, info, &options, &msl::PipelineOptions::default())
            .unwrap_or_else(|e| panic!("MSL {stem}: {e}"));
    let function = translation.entry_point_names[0]
        .clone()
        .unwrap_or_else(|e| panic!("MSL {stem}: {e}"));
    // naga passes workgroup variables to a compute kernel as `threadgroup T& x`
    // arguments sized by the host; wgpu's passthrough path sizes none. Declare
    // them in the kernel body instead, where Metal allocates them statically.
    let text = hoist_threadgroup(&text);
    // naga passes a buffer-size table to any kernel with a runtime-sized array, in
    // the slot after the bindings. Bounds checks are off and no kernel reads
    // `arrayLength`, so the table is never read and the slot stays unbound.
    assert!(
        !text.contains("_buffer_sizes."),
        "MSL {stem}: a kernel reads arrayLength; pass counts in params instead"
    );
    // The double-single library needs IEEE rounding without reassociation or
    // contraction; Metal compiles with fast math unless the source says otherwise.
    let pragma = "#pragma METAL fp math_mode(safe)\n#pragma METAL fp contract(off)\n";
    let text = match text.find("#include <metal_stdlib>") {
        Some(at) => {
            let end = at + text[at..].find('\n').unwrap() + 1;
            format!("{}{pragma}{}", &text[..end], &text[end..])
        }
        None => format!("{pragma}{text}"),
    };
    (text, function)
}

/// The module of one entry point: the other entry points removed, then compacted.
fn single_entry(
    module: &naga::Module,
    entry: &str,
    stem: &str,
) -> (naga::Module, naga::valid::ModuleInfo) {
    let mut module = module.clone();
    module.entry_points.retain(|ep| ep.name == entry);
    naga::compact::compact(&mut module, naga::compact::KeepUnused::No);
    let info = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::all(),
    )
    .validate(&module)
    .unwrap_or_else(|e| panic!("{stem}.{entry} after compaction: {e}"));
    (module, info)
}

/// Move `, threadgroup T& name` kernel arguments into the kernel body.
fn hoist_threadgroup(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut pending: Vec<String> = Vec::new();
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix(", threadgroup ") {
            let (ty, name) = rest.split_once("& ").expect("threadgroup argument");
            pending.push(format!("    threadgroup {ty} {};", name.trim()));
            continue;
        }
        out.push_str(line);
        out.push('\n');
        if line == ") {" && !pending.is_empty() {
            for decl in pending.drain(..) {
                out.push_str(&decl);
                out.push('\n');
            }
        }
    }
    out
}
