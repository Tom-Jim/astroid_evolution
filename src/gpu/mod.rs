//! One compute layer for every target (MS §3.7, §3.15).
//!
//! * Desktop: wgpu on Vulkan (Linux, Windows) or Metal (macOS). The shaders are
//!   compiled at build time (`build.rs`) and loaded as passthrough modules, and a
//!   program that traces rays uses hardware ray queries when the adapter has them.
//! * Browser: the evolution worker cannot wait on a WebGPU promise, so it
//!   serializes each [`Job`] and blocks while the GPU worker runs it on its device.
//!
//! A [`Job`] is a list of operations recorded into one command buffer: local
//! buffers, kernel dispatches, copies and read-backs. Device-resident buffers
//! ([`Res`]) and acceleration structures ([`Accel`]) outlive jobs; their creation
//! and release travel with the next submitted job.

mod exec;

use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Mutex, OnceLock};

use bytemuck::Pod;
use serde::{Deserialize, Serialize};

pub use exec::Exec;

/// Generated by `build.rs`: one constant per entry point, and `ALL`.
pub mod kernels {
    use super::{Bind, BindKind, Code, Kernel, Variant};
    include!(concat!(env!("OUT_DIR"), "/kernels.rs"));
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BindKind {
    Read,
    Write,
    Uniform,
    /// Hardware acceleration structure.
    Accel,
    /// One of the two storage buffers of the software BVH.
    Bvh,
}

#[derive(Clone, Copy, Debug)]
pub struct Bind {
    pub binding: u32,
    pub kind: BindKind,
}

#[derive(Clone, Copy, Debug)]
pub enum Code {
    Spirv(&'static [u8]),
    /// Source and the kernel function's name (naga may rename an entry point).
    Msl(&'static str, &'static str),
    Wgsl(&'static str),
}

#[derive(Clone, Copy, Debug)]
pub struct Variant {
    pub binds: &'static [Bind],
    pub code: Code,
}

/// One compute entry point. Arguments bind by position in binding order; the
/// acceleration structure is one argument in either variant.
#[derive(Debug)]
pub struct Kernel {
    pub id: usize,
    pub name: &'static str,
    pub wg: [u32; 3],
    pub traces: bool,
    pub hw: Variant,
    pub sw: Variant,
}

/// Largest workgroup count of one dispatch dimension.
pub const MAX_GROUPS: u32 = 65_535;

impl Kernel {
    /// Workgroups for `n` threads along x.
    pub fn groups(&self, n: usize) -> [u32; 3] {
        let g = (n as u64).div_ceil(u64::from(self.wg[0])).max(1);
        assert!(
            g <= u64::from(MAX_GROUPS),
            "{}: {n} threads exceed one dispatch",
            self.name
        );
        [g as u32, 1, 1]
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Ref {
    Local(u32),
    Res(u64),
    Accel(u64),
}

#[derive(Debug, Serialize, Deserialize)]
#[doc(hidden)]
pub enum Op {
    NewRes {
        id: u64,
        size: u64,
        data: Option<Vec<u8>>,
    },
    FreeRes {
        id: u64,
    },
    /// Hardware: the triangles. Software: the BVH built on the host as well.
    NewAccel {
        id: u64,
        verts: Vec<f32>,
        tris: Vec<u32>,
        bvh: Option<(Vec<u8>, Vec<u8>)>,
    },
    FreeAccel {
        id: u64,
    },
    Local {
        id: u32,
        size: u64,
        data: Option<Vec<u8>>,
    },
    Write {
        dst: Ref,
        offset: u64,
        data: Vec<u8>,
    },
    Run {
        kernel: usize,
        groups: [u32; 3],
        args: Vec<Ref>,
    },
    Copy {
        src: Ref,
        src_offset: u64,
        dst: Ref,
        dst_offset: u64,
        size: u64,
    },
    Read {
        src: Ref,
        offset: u64,
        size: u64,
    },
}

/// A device argument: a job-local buffer, a resident buffer or a mesh.
#[derive(Clone, Copy, Debug)]
pub struct Buf(Ref);

impl From<&Res> for Buf {
    fn from(r: &Res) -> Self {
        Buf(Ref::Res(r.id))
    }
}

impl From<&Accel> for Buf {
    fn from(a: &Accel) -> Self {
        Buf(Ref::Accel(a.id))
    }
}

/// Operations recorded into one command buffer.
#[derive(Default)]
pub struct Job {
    ops: Vec<Op>,
    locals: u32,
    reads: usize,
}

impl Job {
    pub fn new() -> Self {
        Self::default()
    }

    fn local(&mut self, size: u64, data: Option<Vec<u8>>) -> Buf {
        let id = self.locals;
        self.locals += 1;
        self.ops.push(Op::Local { id, size, data });
        Buf(Ref::Local(id))
    }

    /// A buffer holding `data`.
    pub fn input<T: Pod>(&mut self, data: &[T]) -> Buf {
        let bytes: &[u8] = bytemuck::cast_slice(data);
        self.local(bytes.len() as u64, Some(bytes.to_vec()))
    }

    /// A buffer holding one value (a parameter block).
    pub fn value<T: Pod>(&mut self, value: &T) -> Buf {
        self.input(std::slice::from_ref(value))
    }

    /// A zeroed buffer of `len` elements of `T`.
    pub fn zeros<T: Pod>(&mut self, len: usize) -> Buf {
        self.local((len * std::mem::size_of::<T>()) as u64, None)
    }

    pub fn run(&mut self, kernel: &'static Kernel, groups: [u32; 3], args: &[Buf]) {
        self.ops.push(Op::Run {
            kernel: kernel.id,
            groups,
            args: args.iter().map(|b| b.0).collect(),
        });
    }

    pub fn write<T: Pod>(&mut self, dst: impl Into<Buf>, offset: u64, data: &[T]) {
        self.ops.push(Op::Write {
            dst: dst.into().0,
            offset,
            data: bytemuck::cast_slice(data).to_vec(),
        });
    }

    pub fn copy(
        &mut self,
        src: impl Into<Buf>,
        src_offset: u64,
        dst: impl Into<Buf>,
        dst_offset: u64,
        size: u64,
    ) {
        self.ops.push(Op::Copy {
            src: src.into().0,
            src_offset,
            dst: dst.into().0,
            dst_offset,
            size,
        });
    }

    /// Read `size` bytes back after everything recorded so far; returns the output index.
    pub fn read(&mut self, src: impl Into<Buf>, offset: u64, size: u64) -> usize {
        self.ops.push(Op::Read {
            src: src.into().0,
            offset,
            size,
        });
        self.reads += 1;
        self.reads - 1
    }

    /// Read `len` elements of `T` from the start of `src`.
    pub fn read_all<T: Pod>(&mut self, src: impl Into<Buf>, len: usize) -> usize {
        self.read(src, 0, (len * std::mem::size_of::<T>()) as u64)
    }

    pub fn submit(self) -> Result<Outputs, String> {
        gpu()?.submit(self.ops)
    }
}

/// An argument of [`once`], in binding order.
pub enum Arg<'a> {
    In(&'a [u8]),
    /// A zeroed output of this many bytes, read back.
    Out(usize),
    Res(&'a Res),
    Accel(&'a Accel),
}

/// One dispatch: inputs uploaded, outputs zeroed and read back in order.
pub fn once(
    kernel: &'static Kernel,
    groups: [u32; 3],
    args: &[Arg<'_>],
) -> Result<Vec<Vec<u8>>, String> {
    let mut job = Job::new();
    let mut outs = Vec::new();
    let bufs: Vec<Buf> = args
        .iter()
        .map(|a| match a {
            Arg::In(bytes) => job.input(bytes),
            Arg::Out(size) => {
                let b = job.local(*size as u64, None);
                outs.push((b, *size));
                b
            }
            Arg::Res(r) => Buf::from(*r),
            Arg::Accel(a) => Buf::from(*a),
        })
        .collect();
    job.run(kernel, groups, &bufs);
    for (b, size) in outs {
        job.read(b, 0, size as u64);
    }
    Ok(job.submit()?.0)
}

/// The entry point called `name`.
pub fn kernel(name: &str) -> Result<&'static Kernel, String> {
    kernels::ALL
        .iter()
        .copied()
        .find(|k| k.name == name)
        .ok_or_else(|| format!("no compute entry point `{name}`"))
}

/// Read-back buffers in the order of [`Job::read`].
pub struct Outputs(pub Vec<Vec<u8>>);

impl Outputs {
    pub fn get<T: Pod>(&self, i: usize) -> Vec<T> {
        bytemuck::pod_collect_to_vec(&self.0[i])
    }
}

/// A device-resident buffer. Freed with the next job after it is dropped.
#[derive(Debug)]
pub struct Res {
    id: u64,
    pub size: u64,
}

impl Res {
    pub fn zeroed(size: u64) -> Result<Self, String> {
        let g = gpu()?;
        let id = g.next_id();
        g.defer(Op::NewRes {
            id,
            size,
            data: None,
        });
        Ok(Self { id, size })
    }

    pub fn from_slice<T: Pod>(data: &[T]) -> Result<Self, String> {
        let g = gpu()?;
        let id = g.next_id();
        let bytes: Vec<u8> = bytemuck::cast_slice(data).to_vec();
        let size = bytes.len() as u64;
        g.defer(Op::NewRes {
            id,
            size,
            data: Some(bytes),
        });
        Ok(Self { id, size })
    }
}

impl Drop for Res {
    fn drop(&mut self) {
        if let Some(g) = GPU.get().and_then(|g| g.as_ref().ok()) {
            g.defer(Op::FreeRes { id: self.id });
        }
    }
}

/// A triangle mesh ready for ray queries: a hardware acceleration structure or
/// the software BVH, whichever the device uses.
#[derive(Debug)]
pub struct Accel {
    id: u64,
}

/// Deepest software BVH the traversal stack of `gpu/shader/rt.wesl` holds.
const RT_STACK: usize = 96;

impl Accel {
    /// `verts` are xyz triples, `tris` index triples.
    pub fn new(verts: Vec<f32>, tris: Vec<u32>) -> Result<Self, String> {
        let g = gpu()?;
        let bvh = if g.hw_rt() {
            None
        } else {
            Some(soft_bvh(&verts, &tris)?)
        };
        let id = g.next_id();
        g.defer(Op::NewAccel {
            id,
            verts,
            tris,
            bvh,
        });
        Ok(Self { id })
    }
}

impl Drop for Accel {
    fn drop(&mut self) {
        if let Some(g) = GPU.get().and_then(|g| g.as_ref().ok()) {
            g.defer(Op::FreeAccel { id: self.id });
        }
    }
}

/// Node of the software BVH, as `RtNode` in `gpu/shader/rt.wesl`.
#[repr(C)]
#[derive(Clone, Copy, Pod, bytemuck::Zeroable)]
struct RtNode {
    a_lo: [f32; 3],
    a: u32,
    a_hi: [f32; 3],
    b: u32,
    b_lo: [f32; 3],
    pad0: u32,
    b_hi: [f32; 3],
    pad1: u32,
}

const RT_TRI: u32 = 0x8000_0000;

/// A PLOC tree (Meister and Bittner 2018, `obvhs`) with one triangle per leaf,
/// flattened so each node holds both child boxes; triangles in leaf order.
fn soft_bvh(verts: &[f32], tris: &[u32]) -> Result<(Vec<u8>, Vec<u8>), String> {
    use obvhs::ploc::{PlocBuilder, PlocSearchDistance, SortPrecision};
    use obvhs::triangle::Triangle;
    let v = |i: u32| {
        glam::Vec3A::new(
            verts[3 * i as usize],
            verts[3 * i as usize + 1],
            verts[3 * i as usize + 2],
        )
    };
    let prims: Vec<Triangle> = tris
        .chunks_exact(3)
        .map(|t| Triangle {
            v0: v(t[0]),
            v1: v(t[1]),
            v2: v(t[2]),
        })
        .collect();
    let empty = RtNode {
        a_lo: [1.0; 3],
        a: RT_TRI,
        a_hi: [-1.0; 3],
        b: RT_TRI,
        b_lo: [1.0; 3],
        pad0: 0,
        b_hi: [-1.0; 3],
        pad1: 0,
    };
    let tri_floats = |order: &[u32]| -> Vec<u8> {
        let mut out = Vec::with_capacity(order.len() * 9);
        for &p in order {
            let t = &prims[p as usize];
            out.extend_from_slice(&[
                t.v0.x, t.v0.y, t.v0.z, t.v1.x, t.v1.y, t.v1.z, t.v2.x, t.v2.y, t.v2.z,
            ]);
        }
        bytemuck::cast_slice(&out).to_vec()
    };
    if prims.len() < 2 {
        let mut root = empty;
        if prims.len() == 1 {
            let t = &prims[0];
            root.a = RT_TRI;
            root.a_lo = t.v0.min(t.v1).min(t.v2).into();
            root.a_hi = t.v0.max(t.v1).max(t.v2).into();
        }
        let order: Vec<u32> = (0..prims.len() as u32).collect();
        return Ok((bytemuck::bytes_of(&root).to_vec(), tri_floats(&order)));
    }
    let bvh = PlocBuilder::with_capacity(prims.len()).build(
        PlocSearchDistance::Medium,
        &prims,
        (0..prims.len() as u32).collect(),
        SortPrecision::U64,
        0,
    );
    // Flatten: obvhs inner node `i` has children `first_index`, `first_index + 1`.
    let nodes = &bvh.nodes;
    let mut out = Vec::with_capacity(nodes.len() / 2);
    let mut order = Vec::with_capacity(prims.len());
    let mut depth_max = 0usize;
    // (obvhs node, slot in `out`, depth)
    let mut stack = vec![(0usize, 0usize, 1usize)];
    out.push(empty);
    while let Some((n, slot, depth)) = stack.pop() {
        depth_max = depth_max.max(depth);
        let first = nodes[n].first_index as usize;
        let mut node = empty;
        for (side, c) in [first, first + 1].into_iter().enumerate() {
            let child = &nodes[c];
            let (lo, hi): ([f32; 3], [f32; 3]) = (child.aabb.min.into(), child.aabb.max.into());
            let index = if child.prim_count > 0 {
                order.push(bvh.primitive_indices[child.first_index as usize]);
                RT_TRI | (order.len() as u32 - 1)
            } else {
                out.push(empty);
                stack.push((c, out.len() - 1, depth + 1));
                (out.len() - 1) as u32
            };
            if side == 0 {
                (node.a_lo, node.a_hi, node.a) = (lo, hi, index);
            } else {
                (node.b_lo, node.b_hi, node.b) = (lo, hi, index);
            }
        }
        out[slot] = node;
    }
    if depth_max >= RT_STACK {
        return Err(format!(
            "software BVH depth {depth_max} exceeds the traversal stack"
        ));
    }
    Ok((bytemuck::cast_slice(&out).to_vec(), tri_floats(&order)))
}

enum Backend {
    #[cfg(not(target_arch = "wasm32"))]
    Native(Mutex<Exec>),
    #[cfg(target_arch = "wasm32")]
    Proxy,
}

pub struct Gpu {
    backend: Backend,
    hw_rt: bool,
    /// Resource creation and release waiting for the next job.
    pending: Mutex<Vec<Op>>,
    next: AtomicU64,
    pub adapter: String,
}

static GPU: OnceLock<Result<Gpu, String>> = OnceLock::new();

/// The process-wide device.
pub fn gpu() -> Result<&'static Gpu, String> {
    GPU.get_or_init(Gpu::open).as_ref().map_err(Clone::clone)
}

impl Gpu {
    #[cfg(not(target_arch = "wasm32"))]
    fn open() -> Result<Gpu, String> {
        let soft = std::env::var_os("AE_SOFT_RT").is_some_and(|v| v != "0");
        let exec = pollster::block_on(Exec::native(!soft))?;
        Ok(Gpu {
            hw_rt: exec.hw_rt(),
            adapter: exec.adapter.clone(),
            backend: Backend::Native(Mutex::new(exec)),
            pending: Mutex::new(Vec::new()),
            next: AtomicU64::new(1),
        })
    }

    #[cfg(target_arch = "wasm32")]
    fn open() -> Result<Gpu, String> {
        if !crate::web::worker_mesh() {
            return Err("compute runs in the evolution worker".into());
        }
        Ok(Gpu {
            backend: Backend::Proxy,
            hw_rt: false,
            adapter: "WebGPU (GPU worker)".into(),
            pending: Mutex::new(Vec::new()),
            next: AtomicU64::new(1),
        })
    }

    /// Whether ray tracing runs on hardware ray queries.
    pub fn hw_rt(&self) -> bool {
        self.hw_rt
    }

    fn next_id(&self) -> u64 {
        self.next.fetch_add(1, Ordering::Relaxed)
    }

    fn defer(&self, op: Op) {
        self.pending
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .push(op);
    }

    /// Pending resource operations of every thread run first, under the device
    /// lock, so a buffer created on one thread exists before any job uses it.
    fn take_pending(&self, ops: Vec<Op>) -> Vec<Op> {
        let mut all = std::mem::take(&mut *self.pending.lock().unwrap_or_else(|e| e.into_inner()));
        all.extend(ops);
        all
    }

    fn submit(&self, ops: Vec<Op>) -> Result<Outputs, String> {
        match &self.backend {
            #[cfg(not(target_arch = "wasm32"))]
            Backend::Native(exec) => {
                let mut exec = exec.lock().unwrap_or_else(|e| e.into_inner());
                let all = self.take_pending(ops);
                pollster::block_on(exec.run(all)).map(Outputs)
            }
            #[cfg(target_arch = "wasm32")]
            Backend::Proxy => {
                let all = self.take_pending(ops);
                let bytes = postcard::to_allocvec(&all).map_err(|e| format!("gpu job: {e}"))?;
                let reply = crate::web::call_gpu(&bytes)?;
                let reply: Result<Vec<Vec<u8>>, String> =
                    postcard::from_bytes(&reply).map_err(|e| format!("gpu reply: {e}"))?;
                reply.map(Outputs)
            }
        }
    }
}

/// Page side of the browser proxy: run one serialized job.
#[cfg(target_arch = "wasm32")]
pub async fn serve(exec: &mut Exec, request: &[u8]) -> Vec<u8> {
    let reply: Result<Vec<Vec<u8>>, String> = match postcard::from_bytes::<Vec<Op>>(request) {
        Ok(ops) => exec.run(ops).await,
        Err(e) => Err(format!("gpu job: {e}")),
    };
    postcard::to_allocvec(&reply).unwrap_or_default()
}
